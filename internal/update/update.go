// Package update checks and stages Prism releases for a separate deployment
// supervisor. The HTTP process never replaces its own executable or applies
// database migrations.
package update

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"strconv"
	"strings"
	"time"

	"github.com/mirainya/Prism/pkg/safeurl"
)

const (
	DefaultRepository      = "mirainya/Prism"
	DefaultGitHubBaseURL   = "https://github.com"
	DefaultManifestMaxSize = 1 << 20
	DefaultDownloadMaxSize = 512 << 20
)

var (
	ErrNoUpdate           = errors.New("prism is already up to date")
	ErrInvalidManifest    = errors.New("invalid update manifest")
	ErrSourcesUnavailable = errors.New("all update sources are unavailable")
	ErrAssetUnavailable   = errors.New("no compatible update asset")
	ErrDestinationExists  = errors.New("staging artifact already exists with different content")
)

// Source identifies one manifest and artifact origin. Sources are attempted
// in the order supplied to Options; the first valid manifest wins.
type Source struct {
	Name    string
	BaseURL string
}

// Asset is one platform-specific release archive from manifest.json.
type Asset struct {
	Name      string `json:"name"`
	Platform  string `json:"platform"`
	Arch      string `json:"arch"`
	Size      int64  `json:"size"`
	SHA256    string `json:"sha256"`
	AssetPath string `json:"asset_path"`
}

// Manifest is the release metadata generated by the release workflow.
type Manifest struct {
	Schema    int     `json:"schema"`
	Product   string  `json:"product"`
	Channel   string  `json:"channel"`
	Version   string  `json:"version"`
	Tag       string  `json:"tag"`
	Commit    string  `json:"commit"`
	BuildTime string  `json:"build_time"`
	Assets    []Asset `json:"assets"`
}

// Options controls a Client. A zero value uses the production repository,
// GitHub source, the current process platform, and conservative
// response size limits.
type Options struct {
	Repository      string
	Sources         []Source
	HTTPClient      *http.Client
	CurrentVersion  string
	Channel         string
	Platform        string
	Arch            string
	ManifestMaxSize int64
	DownloadMaxSize int64
}

// Client performs release checks and verified downloads.
type Client struct {
	repository      string
	sources         []Source
	httpClient      *http.Client
	currentVersion  string
	channel         string
	platform        string
	arch            string
	manifestMaxSize int64
	downloadMaxSize int64
}

// CheckResult describes the newest valid release found and whether it is newer
// than the running process. An unversioned development binary is considered
// older than a published release.
type CheckResult struct {
	CurrentVersion  string
	LatestVersion   string
	UpdateAvailable bool
	Source          string
	Manifest        Manifest
}

// DownloadResult describes a verified archive written to staging.
type DownloadResult struct {
	Path      string
	Source    string
	SourceURL string
	Version   string
	Asset     Asset
	Size      int64
	SHA256    string
}

// NewClient validates update sources and applies defaults.
func NewClient(options Options) (*Client, error) {
	repository := strings.TrimSpace(options.Repository)
	if repository == "" {
		repository = DefaultRepository
	}
	if err := validateRepository(repository); err != nil {
		return nil, err
	}
	sources := options.Sources
	if len(sources) == 0 {
		sources = []Source{
			{Name: "github", BaseURL: DefaultGitHubBaseURL},
		}
	}
	normalized := make([]Source, 0, len(sources))
	seen := make(map[string]struct{}, len(sources))
	for index, source := range sources {
		name := strings.TrimSpace(source.Name)
		if name == "" {
			name = fmt.Sprintf("source-%d", index+1)
		}
		base, err := normalizeBaseURL(source.BaseURL)
		if err != nil {
			return nil, fmt.Errorf("update source %q: %w", name, err)
		}
		if _, exists := seen[base]; exists {
			continue
		}
		seen[base] = struct{}{}
		normalized = append(normalized, Source{Name: name, BaseURL: base})
	}
	if len(normalized) == 0 {
		return nil, ErrSourcesUnavailable
	}
	httpClient := options.HTTPClient
	if httpClient == nil {
		httpClient = safeurl.NewClient(60 * time.Second)
	}
	manifestMaxSize := options.ManifestMaxSize
	if manifestMaxSize <= 0 {
		manifestMaxSize = DefaultManifestMaxSize
	}
	downloadMaxSize := options.DownloadMaxSize
	if downloadMaxSize <= 0 {
		downloadMaxSize = DefaultDownloadMaxSize
	}
	if manifestMaxSize > downloadMaxSize {
		return nil, fmt.Errorf("manifest max size exceeds download max size")
	}
	platform := strings.TrimSpace(options.Platform)
	if platform == "" {
		platform = runtime.GOOS
	}
	arch := strings.TrimSpace(options.Arch)
	if arch == "" {
		arch = runtime.GOARCH
	}
	channel := strings.TrimSpace(options.Channel)
	if channel == "" {
		channel = "stable"
	}
	if channel != "stable" && channel != "prerelease" {
		return nil, fmt.Errorf("unsupported update channel %q", channel)
	}
	return &Client{
		repository: repository, sources: normalized, httpClient: httpClient,
		currentVersion: strings.TrimSpace(options.CurrentVersion), channel: channel, platform: platform, arch: arch,
		manifestMaxSize: manifestMaxSize, downloadMaxSize: downloadMaxSize,
	}, nil
}

// Check uses the first valid manifest in source priority order.
func (c *Client) Check(ctx context.Context) (CheckResult, error) {
	manifest, source, err := c.fetchManifest(ctx)
	if err != nil {
		return CheckResult{}, err
	}
	current := strings.TrimSpace(c.currentVersion)
	updateAvailable := true
	if currentVersion, parseErr := parseSemVersion(current); parseErr == nil {
		latestVersion, _ := parseSemVersion(manifest.Version)
		updateAvailable = compareSemVersion(latestVersion, currentVersion) > 0
	}
	return CheckResult{
		CurrentVersion: current, LatestVersion: manifest.Version,
		UpdateAvailable: updateAvailable, Source: source.Name, Manifest: manifest,
	}, nil
}

// Download fetches and verifies the compatible release archive into targetDir.
// It never extracts, replaces, restarts, or runs migrations.
func (c *Client) Download(ctx context.Context, targetDir string) (DownloadResult, error) {
	manifest, source, err := c.fetchManifest(ctx)
	if err != nil {
		return DownloadResult{}, err
	}
	current := strings.TrimSpace(c.currentVersion)
	if currentVersion, parseErr := parseSemVersion(current); parseErr == nil {
		latestVersion, _ := parseSemVersion(manifest.Version)
		if compareSemVersion(latestVersion, currentVersion) <= 0 {
			return DownloadResult{}, ErrNoUpdate
		}
	}
	asset, err := c.compatibleAsset(manifest)
	if err != nil {
		return DownloadResult{}, err
	}
	if strings.TrimSpace(targetDir) == "" {
		targetDir = filepath.Join(".update", "staging", "v"+manifest.Version)
	}
	if err := os.MkdirAll(targetDir, 0o750); err != nil {
		return DownloadResult{}, fmt.Errorf("create update staging directory: %w", err)
	}
	tried := make([]error, 0, len(c.sources))
	for _, candidateSource := range c.sources {
		candidateManifest := manifest
		candidateAsset := asset
		if candidateSource.BaseURL != source.BaseURL {
			candidateManifest, err = c.fetchManifestFromSource(ctx, candidateSource)
			if err != nil {
				tried = append(tried, fmt.Errorf("%s manifest: %w", candidateSource.Name, err))
				continue
			}
			// A fallback source must describe the same release selected by the
			// first valid manifest. Never combine one source's metadata with
			// another source's version or digest.
			if candidateManifest.Version != manifest.Version || candidateManifest.Tag != manifest.Tag {
				tried = append(tried, fmt.Errorf("%s manifest describes %s instead of %s", candidateSource.Name, candidateManifest.Version, manifest.Version))
				continue
			}
			candidateAsset, err = c.compatibleAsset(candidateManifest)
			if err != nil || candidateAsset.Name != asset.Name || candidateAsset.Size != asset.Size || candidateAsset.SHA256 != asset.SHA256 {
				tried = append(tried, fmt.Errorf("%s manifest asset does not match selected release", candidateSource.Name))
				continue
			}
		}
		result, downloadErr := c.downloadAsset(ctx, targetDir, candidateSource, candidateManifest, candidateAsset)
		if downloadErr == nil {
			return result, nil
		}
		if errors.Is(downloadErr, ErrDestinationExists) {
			return DownloadResult{}, downloadErr
		}
		tried = append(tried, downloadErr)
	}
	if len(tried) == 0 {
		return DownloadResult{}, ErrAssetUnavailable
	}
	return DownloadResult{}, fmt.Errorf("%w: %w", ErrAssetUnavailable, errors.Join(tried...))
}

func (c *Client) downloadAsset(ctx context.Context, targetDir string, source Source, manifest Manifest, asset Asset) (DownloadResult, error) {
	assetURL, err := source.assetURL(asset.AssetPath)
	if err != nil {
		return DownloadResult{}, err
	}
	request, err := http.NewRequestWithContext(ctx, http.MethodGet, assetURL, nil)
	if err != nil {
		return DownloadResult{}, fmt.Errorf("create update download request: %w", err)
	}
	response, err := c.httpClient.Do(request)
	if err != nil {
		return DownloadResult{}, fmt.Errorf("download update asset from %s: %w", source.Name, err)
	}
	defer response.Body.Close()
	if response.StatusCode < http.StatusOK || response.StatusCode >= http.StatusMultipleChoices {
		return DownloadResult{}, fmt.Errorf("download update asset from %s returned HTTP %d", source.Name, response.StatusCode)
	}
	if response.ContentLength > c.downloadMaxSize || response.ContentLength >= 0 && response.ContentLength != asset.Size {
		return DownloadResult{}, fmt.Errorf("update asset size does not match manifest: got %d, want %d", response.ContentLength, asset.Size)
	}
	temporary, err := os.CreateTemp(targetDir, "."+asset.Name+".part-*")
	if err != nil {
		return DownloadResult{}, fmt.Errorf("create update staging file: %w", err)
	}
	temporaryPath := temporary.Name()
	cleanup := func() {
		_ = temporary.Close()
		_ = os.Remove(temporaryPath)
	}
	hasher := sha256.New()
	limited := io.LimitReader(response.Body, c.downloadMaxSize+1)
	bytesWritten, copyErr := io.Copy(io.MultiWriter(temporary, hasher), limited)
	if copyErr != nil {
		cleanup()
		return DownloadResult{}, fmt.Errorf("write update staging file: %w", copyErr)
	}
	if bytesWritten > c.downloadMaxSize || bytesWritten != asset.Size {
		cleanup()
		return DownloadResult{}, fmt.Errorf("update asset size does not match manifest: got %d, want %d", bytesWritten, asset.Size)
	}
	digest := hex.EncodeToString(hasher.Sum(nil))
	if digest != asset.SHA256 {
		cleanup()
		return DownloadResult{}, fmt.Errorf("update asset SHA256 mismatch: got %s, want %s", digest, asset.SHA256)
	}
	if err := temporary.Sync(); err != nil {
		cleanup()
		return DownloadResult{}, fmt.Errorf("sync update staging file: %w", err)
	}
	if err := temporary.Close(); err != nil {
		_ = os.Remove(temporaryPath)
		return DownloadResult{}, fmt.Errorf("close update staging file: %w", err)
	}
	finalPath := filepath.Join(targetDir, asset.Name)
	if existing, readErr := os.Open(finalPath); readErr == nil {
		existingDigest, existingSize, digestErr := fileDigest(existing)
		_ = existing.Close()
		if digestErr == nil && existingSize == asset.Size && existingDigest == asset.SHA256 {
			_ = os.Remove(temporaryPath)
			return DownloadResult{Path: finalPath, Source: source.Name, SourceURL: assetURL, Version: manifest.Version, Asset: asset, Size: asset.Size, SHA256: digest}, nil
		}
		_ = os.Remove(temporaryPath)
		return DownloadResult{}, ErrDestinationExists
	} else if !errors.Is(readErr, os.ErrNotExist) {
		_ = os.Remove(temporaryPath)
		return DownloadResult{}, fmt.Errorf("inspect existing update artifact: %w", readErr)
	}
	if err := os.Rename(temporaryPath, finalPath); err != nil {
		_ = os.Remove(temporaryPath)
		return DownloadResult{}, fmt.Errorf("finalize update staging file: %w", err)
	}
	return DownloadResult{Path: finalPath, Source: source.Name, SourceURL: assetURL, Version: manifest.Version, Asset: asset, Size: bytesWritten, SHA256: digest}, nil
}

func (c *Client) fetchManifest(ctx context.Context) (Manifest, Source, error) {
	errorsSeen := make([]error, 0, len(c.sources))
	for _, source := range c.sources {
		manifestURL, err := source.manifestURL(c.repository)
		if err != nil {
			errorsSeen = append(errorsSeen, fmt.Errorf("%s: %w", source.Name, err))
			continue
		}
		request, err := http.NewRequestWithContext(ctx, http.MethodGet, manifestURL, nil)
		if err != nil {
			errorsSeen = append(errorsSeen, fmt.Errorf("%s: %w", source.Name, err))
			continue
		}
		request.Header.Set("Cache-Control", "no-cache")
		request.Header.Set("Pragma", "no-cache")
		response, requestErr := c.httpClient.Do(request)
		if requestErr != nil {
			errorsSeen = append(errorsSeen, fmt.Errorf("%s: %w", source.Name, requestErr))
			continue
		}
		body, readErr := readLimited(response.Body, c.manifestMaxSize)
		_ = response.Body.Close()
		if readErr != nil {
			errorsSeen = append(errorsSeen, fmt.Errorf("%s: %w", source.Name, readErr))
			continue
		}
		if response.StatusCode < http.StatusOK || response.StatusCode >= http.StatusMultipleChoices {
			errorsSeen = append(errorsSeen, fmt.Errorf("%s returned HTTP %d", source.Name, response.StatusCode))
			continue
		}
		var manifest Manifest
		if err := json.Unmarshal(body, &manifest); err != nil {
			errorsSeen = append(errorsSeen, fmt.Errorf("%s manifest JSON: %w", source.Name, err))
			continue
		}
		if err := validateManifest(manifest, c.repository, c.downloadMaxSize); err != nil {
			errorsSeen = append(errorsSeen, fmt.Errorf("%s manifest: %w", source.Name, err))
			continue
		}
		if manifest.Channel != c.channel {
			errorsSeen = append(errorsSeen, fmt.Errorf("%s manifest channel %q is not selected channel %q", source.Name, manifest.Channel, c.channel))
			continue
		}
		return manifest, source, nil
	}
	if len(errorsSeen) == 0 {
		return Manifest{}, Source{}, ErrSourcesUnavailable
	}
	return Manifest{}, Source{}, fmt.Errorf("%w: %w", ErrSourcesUnavailable, errors.Join(errorsSeen...))
}

// fetchManifestFromSource reads and validates one source without selecting a
// release. It is used when an already selected manifest's asset needs a
// secondary source after the primary archive endpoint fails.
func (c *Client) fetchManifestFromSource(ctx context.Context, source Source) (Manifest, error) {
	manifestURL, err := source.manifestURL(c.repository)
	if err != nil {
		return Manifest{}, err
	}
	request, err := http.NewRequestWithContext(ctx, http.MethodGet, manifestURL, nil)
	if err != nil {
		return Manifest{}, err
	}
	request.Header.Set("Cache-Control", "no-cache")
	request.Header.Set("Pragma", "no-cache")
	response, err := c.httpClient.Do(request)
	if err != nil {
		return Manifest{}, err
	}
	body, readErr := readLimited(response.Body, c.manifestMaxSize)
	_ = response.Body.Close()
	if readErr != nil {
		return Manifest{}, readErr
	}
	if response.StatusCode < http.StatusOK || response.StatusCode >= http.StatusMultipleChoices {
		return Manifest{}, fmt.Errorf("returned HTTP %d", response.StatusCode)
	}
	var manifest Manifest
	if err := json.Unmarshal(body, &manifest); err != nil {
		return Manifest{}, fmt.Errorf("manifest JSON: %w", err)
	}
	if err := validateManifest(manifest, c.repository, c.downloadMaxSize); err != nil {
		return Manifest{}, err
	}
	return manifest, nil
}

func (c *Client) compatibleAsset(manifest Manifest) (Asset, error) {
	for _, asset := range manifest.Assets {
		if asset.Platform == c.platform && asset.Arch == c.arch {
			return asset, nil
		}
	}
	return Asset{}, fmt.Errorf("%w for %s/%s", ErrAssetUnavailable, c.platform, c.arch)
}

func (s Source) manifestURL(repository string) (string, error) {
	return joinURL(s.BaseURL, repository+"/releases/latest/download/manifest.json")
}

func (s Source) assetURL(assetPath string) (string, error) {
	return joinURL(s.BaseURL, assetPath)
}

func joinURL(base, path string) (string, error) {
	if strings.HasPrefix(path, "/") || strings.Contains(path, "\\") || strings.Contains(path, "..") {
		return "", fmt.Errorf("invalid update path %q", path)
	}
	return strings.TrimRight(base, "/") + "/" + path, nil
}

func normalizeBaseURL(raw string) (string, error) {
	parsed, err := url.Parse(strings.TrimSpace(raw))
	if err != nil || parsed == nil || (parsed.Scheme != "https" && parsed.Scheme != "http") || parsed.Hostname() == "" || parsed.User != nil || parsed.RawQuery != "" || parsed.Fragment != "" {
		return "", fmt.Errorf("invalid base URL")
	}
	parsed.Path = strings.TrimRight(parsed.Path, "/")
	parsed.RawPath = ""
	return parsed.String(), nil
}

func validateRepository(repository string) error {
	parts := strings.Split(repository, "/")
	if len(parts) != 2 || parts[0] == "" || parts[1] == "" || strings.ContainsAny(repository, `\\?#`) || strings.Contains(repository, "..") {
		return fmt.Errorf("invalid repository %q", repository)
	}
	return nil
}

func readLimited(reader io.Reader, maximum int64) ([]byte, error) {
	if maximum <= 0 {
		return nil, fmt.Errorf("invalid response limit")
	}
	data, err := io.ReadAll(io.LimitReader(reader, maximum+1))
	if err != nil {
		return nil, fmt.Errorf("read response: %w", err)
	}
	if int64(len(data)) > maximum {
		return nil, fmt.Errorf("response exceeds %d bytes", maximum)
	}
	return data, nil
}

func fileDigest(file io.Reader) (string, int64, error) {
	hasher := sha256.New()
	bytesRead, err := io.Copy(hasher, file)
	if err != nil {
		return "", 0, err
	}
	return hex.EncodeToString(hasher.Sum(nil)), bytesRead, nil
}

var semverPattern = regexp.MustCompile(`^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(?:-([0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?(?:\+[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?$`)

type semVersion struct {
	major, minor, patch int64
	pre                 []string
}

func parseSemVersion(raw string) (semVersion, error) {
	raw = strings.TrimPrefix(strings.TrimSpace(raw), "v")
	matches := semverPattern.FindStringSubmatch(raw)
	if matches == nil {
		return semVersion{}, fmt.Errorf("invalid semantic version %q", raw)
	}
	major, _ := strconv.ParseInt(matches[1], 10, 64)
	minor, _ := strconv.ParseInt(matches[2], 10, 64)
	patch, _ := strconv.ParseInt(matches[3], 10, 64)
	var pre []string
	if matches[4] != "" {
		pre = strings.Split(matches[4], ".")
		for _, identifier := range pre {
			if len(identifier) > 1 && identifier[0] == '0' && allDigits(identifier) {
				return semVersion{}, fmt.Errorf("invalid semantic version %q", raw)
			}
		}
	}
	return semVersion{major: major, minor: minor, patch: patch, pre: pre}, nil
}

func allDigits(value string) bool {
	for _, character := range value {
		if character < '0' || character > '9' {
			return false
		}
	}
	return value != ""
}

func compareSemVersion(left, right semVersion) int {
	for _, values := range [][2]int64{{left.major, right.major}, {left.minor, right.minor}, {left.patch, right.patch}} {
		if values[0] < values[1] {
			return -1
		}
		if values[0] > values[1] {
			return 1
		}
	}
	if len(left.pre) == 0 && len(right.pre) == 0 {
		return 0
	}
	if len(left.pre) == 0 {
		return 1
	}
	if len(right.pre) == 0 {
		return -1
	}
	for index := 0; index < len(left.pre) && index < len(right.pre); index++ {
		leftID, rightID := left.pre[index], right.pre[index]
		leftNumeric, rightNumeric := allDigits(leftID), allDigits(rightID)
		if leftNumeric && rightNumeric {
			leftNumber, _ := strconv.ParseInt(leftID, 10, 64)
			rightNumber, _ := strconv.ParseInt(rightID, 10, 64)
			if leftNumber < rightNumber {
				return -1
			}
			if leftNumber > rightNumber {
				return 1
			}
			continue
		}
		if leftNumeric != rightNumeric {
			if leftNumeric {
				return -1
			}
			return 1
		}
		if leftID < rightID {
			return -1
		}
		if leftID > rightID {
			return 1
		}
	}
	if len(left.pre) < len(right.pre) {
		return -1
	}
	if len(left.pre) > len(right.pre) {
		return 1
	}
	return 0
}

func validateManifest(manifest Manifest, repository string, maxAssetSize int64) error {
	if manifest.Schema != 1 || manifest.Product != "Prism" || manifest.Channel != "stable" && manifest.Channel != "prerelease" {
		return ErrInvalidManifest
	}
	if _, err := parseSemVersion(manifest.Version); err != nil || manifest.Tag != "v"+manifest.Version {
		return fmt.Errorf("%w: invalid version/tag", ErrInvalidManifest)
	}
	if len(manifest.Commit) != 40 || !regexp.MustCompile(`^[0-9a-f]{40}$`).MatchString(manifest.Commit) {
		return fmt.Errorf("%w: invalid commit", ErrInvalidManifest)
	}
	if buildTime, err := time.Parse(time.RFC3339, manifest.BuildTime); err != nil || buildTime.IsZero() {
		return fmt.Errorf("%w: invalid build_time", ErrInvalidManifest)
	}
	if len(manifest.Assets) == 0 || len(manifest.Assets) > 16 {
		return fmt.Errorf("%w: invalid asset count", ErrInvalidManifest)
	}
	seen := make(map[string]struct{}, len(manifest.Assets))
	for _, asset := range manifest.Assets {
		if asset.Name == "" || filepath.Base(asset.Name) != asset.Name || strings.ContainsAny(asset.Name, `/\\`) || strings.Contains(asset.Name, "..") {
			return fmt.Errorf("%w: invalid asset name", ErrInvalidManifest)
		}
		if asset.Platform != "linux" && asset.Platform != "windows" || asset.Arch != "amd64" {
			return fmt.Errorf("%w: unsupported asset platform", ErrInvalidManifest)
		}
		if asset.Size <= 0 || asset.Size > maxAssetSize {
			return fmt.Errorf("%w: invalid asset size", ErrInvalidManifest)
		}
		if !regexp.MustCompile(`^[0-9a-f]{64}$`).MatchString(asset.SHA256) {
			return fmt.Errorf("%w: invalid asset SHA256", ErrInvalidManifest)
		}
		expectedPath := repository + "/releases/download/" + manifest.Tag + "/" + asset.Name
		if asset.AssetPath != expectedPath {
			return fmt.Errorf("%w: invalid asset path", ErrInvalidManifest)
		}
		key := asset.Platform + "/" + asset.Arch
		if _, exists := seen[key]; exists {
			return fmt.Errorf("%w: duplicate asset platform", ErrInvalidManifest)
		}
		seen[key] = struct{}{}
	}
	return nil
}
